#!/usr/bin/env node
// Generates src/styles/tokens.css from src/data/design-tokens-v3.json (v3 values from docs/design-v3/tokens.json, plus
// the `legacy` map that keeps the v2 variable names used by components pointing at v3 values) and fails if any WCAG
// contrast pair in the token file does not meet its required ratio.
// Runs automatically before `npm run dev` / `npm run build`. Usage: node scripts/gen-tokens.js
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';

const GAME = path.resolve(new URL('..', import.meta.url).pathname);
export const TOKENS_PATH = path.join(GAME, 'src/data/design-tokens-v3.json');
const CSS_PATH = path.join(GAME, 'src/styles/tokens.css');

const hex = (h) => { const v = h.replace('#', ''); return [0, 2, 4].map((i) => parseInt(v.slice(i, i + 2), 16) / 255); };
const lin = (c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const lum = (h) => { const [r, g, b] = hex(h).map(lin); return 0.2126 * r + 0.7152 * g + 0.0722 * b; };
export const contrastRatio = (a, b) => { const x = lum(a), y = lum(b); return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05); };
export const REQUIRED = { body: 4.5, large: 3, 'non-text': 3, ui: 3, exempt: 0 };

/** Resolves "{color.x}" / "{radius.x}" / "{border.x}" / "{legacy.x}" references to raw values. */
export function resolve(T, v) {
  return String(v).replace(/\{([a-z]+)\.([a-z0-9-]+)\}/g, (m, group, key) => {
    const src = group === 'legacy' ? T.legacy.color : T[group];
    if (!src || !(key in src)) throw new Error(`unknown token reference ${m}`);
    return resolve(T, src[key]);
  });
}

/** Same reference, as a CSS value: v3 colours/radii become var(), so the alias follows the v3 token. */
function cssRef(T, v) {
  return String(v).replace(/\{([a-z]+)\.([a-z0-9-]+)\}/g, (m, group, key) => {
    if (group === 'color') return `var(--c-${key})`;
    if (group === 'radius') return `var(--r-${key})`;
    return resolve(T, m);
  });
}

/** Recomputes every contrast pair listed in the tokens. Returns [{ name, kind, ratio, need, pass }]. */
export function contrastChecks(tokens) {
  return tokens.contrast.map((c) => {
    const ratio = Math.round(contrastRatio(resolve(tokens, c.fg), resolve(tokens, c.bg)) * 100) / 100;
    const need = REQUIRED[c.kind];
    return { name: c.name, kind: c.kind, ratio, need, pass: ratio >= need };
  });
}

export function tokensCss(T) {
  const L = T.legacy;
  let css = '/* GENERATED by scripts/gen-tokens.js from src/data/design-tokens-v3.json - do not edit */\n:root{\n';
  css += '  /* v3 colour */\n';
  for (const [k, v] of Object.entries(T.color)) {
    if (Array.isArray(v)) v.forEach((o, i) => { css += `  --o-${k.replace(/-opacity$/, '')}-${i + 1}:${o};\n`; });
    else css += `  --c-${k}:${v};\n`;
  }
  css += '  /* v3 type */\n';
  css += `  --f-sans:${T.font.sans};\n  --f-mono:${T.font.mono};\n`;
  for (const [k, v] of Object.entries(T.type)) {
    if (typeof v === 'number') { css += `  --fs-${k}:${v}px;\n`; continue; }
    css += `  --fs-${k}:${v.size}px;\n  --fw-${k}:${v.weight};\n  --lh-${k}:${v.line}px;\n`;
    if (v.min) css += `  --fs-${k}-min:${v.min}px;\n`;
  }
  css += '  /* v3 spacing, radius, border */\n';
  for (const [k, v] of Object.entries(T.space)) css += `  --sp-${k}:${v}px;\n`;
  for (const [k, v] of Object.entries(T.radius)) css += `  --r-${k}:${v}px;\n`;
  for (const [k, v] of Object.entries(T.border)) css += `  --b-${k}:${v}px;\n`;
  css += '  /* v3 stacking (z), then the extra layers v3 does not name (legacy.z, slotted between them) */\n';
  for (const [k, v] of Object.entries(T.z)) css += `  --z-${k}:${v};\n`;
  for (const [k, v] of Object.entries(L.z)) {
    if (k in T.z) throw new Error(`legacy.z.${k} collides with the v3 z token of the same name`);
    css += `  --z-${k}:${v};\n`;
  }
  css += '  /* v2 names still used by components, mapped to v3 values (legacy) */\n';
  for (const [k, v] of Object.entries(L.color)) css += `  --c-${k}:${cssRef(T, v)};\n`;
  for (const [t, v] of Object.entries(L.tier)) css += `  --t${t}:${cssRef(T, v.fill)};\n  --t${t}-ink:${cssRef(T, v.ink)};\n`;
  for (const [k, v] of Object.entries(L.radius)) css += `  --r-${k}:${cssRef(T, v)};\n`;
  for (const [k, v] of Object.entries(L.shadow)) css += `  --sh-${k}:${cssRef(T, v)};\n`;
  css += '  --f-display:var(--f-sans);\n  --f-ui:var(--f-sans);\n}\n';
  return css;
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  const T = JSON.parse(readFileSync(TOKENS_PATH, 'utf8'));
  const fails = contrastChecks(T).filter((c) => !c.pass);
  if (fails.length) {
    console.error('CONTRAST FAIL', fails);
    process.exit(1);
  }
  mkdirSync(path.dirname(CSS_PATH), { recursive: true });
  writeFileSync(CSS_PATH, tokensCss(T));
  console.log(`tokens.css written; ${T.contrast.length} contrast checks pass`);
}
