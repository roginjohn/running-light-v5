// v5 batch 7 artifacts: every mocked state at 1920x1080, 390x844 and 360x640, rendered from dist/ with the mock's bets, into
// docs/design-v5/batch-7/, plus contrast.md, the lowest measured ratio of each text and state pair over all audited states.
// Fails on page overflow, a clipped control or text, or any audit finding. Run: npm run screenshots:batch7
import path from 'node:path';
import { mkdirSync, writeFileSync } from 'node:fs';
import { startServer, launch, openGame } from './harness.js';
import { SCENES, AUDIT_ONLY, VIEWPORTS, audit, layoutCheck, pause } from './a11y-audit.js';

const OUT = path.resolve(new URL('../../docs/design-v5/batch-7/', import.meta.url).pathname);
const { server, url } = await startServer();
const browser = await launch();
mkdirSync(OUT, { recursive: true });
const text = new Map(), nonText = new Map();
const low = (m, k, r) => { if (!m.has(k) || m.get(k) > r) m.set(k, r); };
let exempt = 0;
const shots = [];
try {
  for (const [w, h, touch] of VIEWPORTS) {
    for (const [name, scene] of Object.entries({ ...SCENES, ...AUDIT_ONLY })) {
      const page = await openGame(browser, url, { seed: 1, timeScale: 8, width: w, height: h, touch });
      await scene(page);
      await pause();
      const c = await page.evaluate(layoutCheck);
      const a = await page.evaluate(audit, { touch });
      if (c.scrollW > c.w || c.scrollH > c.h || c.off.length || c.clipped.length) throw new Error(`layout check failed: ${name} at ${w}x${h}: ${JSON.stringify(c)}`);
      const bad = [...a.text, ...a.nonText, ...a.font, ...a.body, ...a.tap];
      if (bad.length) throw new Error(`audit failed: ${name} at ${w}x${h}:\n${bad.join('\n')}`);
      for (const [k, r] of a.textPairs) low(text, k, r);
      for (const [k, r] of a.nonTextPairs) low(nonText, k, r);
      exempt += a.exempt;
      if (name in SCENES) {
        await page.screenshot({ path: path.join(OUT, `${name}-${w}x${h}.png`) });
        shots.push(`${name}-${w}x${h}`);
      }
      if (page.__issues.length) throw new Error(page.__issues.join('\n'));
      await page.close();
    }
  }
} finally {
  await browser.close();
  server.close();
}
const rows = (m) => [...m].sort((a, b) => a[1] - b[1]).map(([k, r]) => `| ${k.replace(/\|/g, '\\|')} | ${r.toFixed(2)} |`).join('\n');
const states = Object.keys({ ...SCENES, ...AUDIT_ONLY }).join(', ');
writeFileSync(path.join(OUT, 'contrast.md'), `# v5 batch 7 contrast audit

Generated by \`npm run screenshots:batch7\` from the rendered page; \`npm run test:ui\` (test/ui/a11y.test.js) fails on the same checks.
Each ratio is the lowest measured at 1920x1080, 390x844 and 360x640 in these states: ${states}. Fades are composited over what is behind them.

- Text needs 4.5:1 at every size. Large text gets no 3:1 allowance.
- Disabled controls are exempt, as in WCAG 1.4.3 (${exempt} text measurements skipped: disabled secondary buttons, chips, bar icons and switches).
- Non-text means borders, fills and rings that carry a state or identify a control. Plain dividers and the hairline around a control that is already identified by its text are decorative and not listed.

## Non-text (needs 3:1)
| Cue / against | Lowest ratio |
|---|---|
${rows(nonText)}

## Text (needs 4.5:1)
| Element and colour | Lowest ratio |
|---|---|
${rows(text)}
`);
console.log(`${shots.length} screenshots and contrast.md written to ${OUT}`);
